5. 운영자는 서비스 제공에 필요한 범위를 넘어 이용자 콘텐츠를 출판, 판매하거나 제3자에게 공개하지 않습니다. 법령에 따른 의무가 있거나 회원이 별도로 요청·동의한 경우는 예외로 합니다.
6. 운영자는 법령이 허용하는 범위에서 회원이 자신의 창작 활동을 위해 AI 결과를 확인, 수정, 복제하고 이용할 수 있도록 합니다. 운영자는 AI 결과에 대한 독점적 권리를 주장하지 않으며, AI의 특성상 다른 이용자에게 동일하거나 유사한 결과가 생성될 수 있습니다.
7. 이용계약이 종료되거나 회원이 삭제를 요청하면 운영자는 확정된 개인정보처리방침과 실제 구현된 파기 절차에 따라 이용자 콘텐츠를 처리합니다. 법령상 보관 의무가 있는 자료는 해당 기간 동안 분리 보관할 수 있습니다.
8. 회원은 중요한 원고의 원본과 필요한 백업을 별도로 보관해야 합니다. 운영자는 합리적인 보호조치를 취하지만 무료 베타에서 영구 보관 수단을 제공하는 것은 아닙니다.

## 제9조(AI 분석과 결과의 한계)

1. AI 결과는 확률적 모델이 생성한 창작 보조 제안으로, 부정확하거나 불완전하거나 동일한 입력에도 달라질 수 있습니다.
2. 운영자는 AI 결과가 사실과 완전히 일치하거나 특정한 창작 목적에 적합하고 제3자의 권리를 침해하지 않는다고 보증하지 않습니다.
3. 회원은 AI 결과와 원문 근거를 직접 검토하고 필요한 경우 수정한 뒤 사용할 책임이 있습니다. 서비스는 회원의 검토·확정 없이 회원에게 법적 또는 이에 준하는 중대한 효과를 발생시키는 자동 결정을 하지 않습니다.
4. AI 분석을 위해 이용자 콘텐츠의 전부가 아닌 필요한 원문 구간과 관련 정보가 국외 AI 처리 사업자에게 전송될 수 있습니다. 수탁자, 이전 국가, 목적, 방법과 보유기간은 개인정보처리방침에 공개합니다.
5. 회원은 주민등록번호, 건강정보, 계좌정보와 같이 서비스 제공에 필요하지 않은 개인정보 또는 제3자의 비공개 정보를 원고에 포함하지 않도록 주의해야 합니다.

## 제10조(회원의 의무와 금지행위)

회원은 다음 행위를 해서는 안 됩니다.

1. 법령, 이 약관, 서비스 안내 또는 타인의 권리를 위반하는 행위
2. 타인의 계정·연락처·원고를 권한 없이 사용하거나 자신을 타인으로 가장하는 행위
3. 저작권, 개인정보, 영업비밀, 명예와 그 밖의 권리를 침해하는 콘텐츠를 업로드하는 행위
4. 불법정보, 악성코드 또는 서비스 운영을 방해할 수 있는 자료를 전송하는 행위
5. 서비스의 인증, 접근통제, 사용량 제한 또는 보안조치를 우회하는 행위
6. 자동화된 수단으로 과도한 요청을 보내거나 서비스의 안정성을 해치는 행위
7. 법령상 허용되는 범위를 넘어 서비스를 역설계하거나 소스·모델·비공개 데이터를 추출하려는 행위
8. AI 결과를 운영자 또는 제3자의 공식 판단이나 보증인 것처럼 오인시키는 행위
9. 그 밖에 운영자가 합리적인 근거로 서비스의 안전과 다른 이용자의 이용을 현저히 방해한다고 판단하는 행위

## 제11조(이용 제한과 계약 해지)

1. 회원이 제10조를 위반하거나 서비스의 안전을 위협한 경우 운영자는 위반의 성격과 정도에 따라 경고, 기능 제한, 일시 정지 또는 이용계약 해지를 할 수 있습니다.
2. 운영자는 원칙적으로 제한의 이유, 범위와 기간을 사전에 알리고 상당한 기간을 정하여 시정 기회를 제공합니다. 긴급한 보안 위협, 중대한 권리 침해 또는 법령상 의무가 있는 경우에는 먼저 제한한 뒤 지체 없이 알릴 수 있습니다.
3. 회원은 제한 조치에 대해 제3조의 연락처로 이의를 제기할 수 있으며, 운영자는 합리적인 기간 안에 검토 결과를 안내합니다.
4. 회원은 서비스에서 제공하는 방법 또는 제3조의 연락처를 통해 언제든 이용계약 해지를 요청할 수 있습니다.
5. 회원이 탈퇴를 확정하면 취소 유예기간 없이 즉시 계정 이용과 기존 세션을 차단하고 삭제 절차를 시작합니다. 운영계의 계정·원고·설정·AI 결과는 24시간 이내 삭제하며, 격리 백업은 운영계 복원에 사용하지 않고 최대 30일 이내 자동 만료합니다. 원고 내용을 포함하지 않는 삭제 처리 감사 기록은 재시도와 분쟁 대응을 위해 1년간 분리 보관할 수 있습니다.

## 제12조(서비스의 변경·중단)

1. 운영자는 서비스 개선, 점검, 보안, 법령·정책 변경 또는 외부 인프라·AI 제공자의 사정으로 서비스의 전부 또는 일부를 변경하거나 일시 중단할 수 있습니다.
2. 예정된 점검이나 회원에게 중대한 영향을 주는 변경·중단은 그 사유와 기간을 합리적인 기간 전에 서비스에 알립니다.
3. 장애, 보안사고, 천재지변, 통신망 장애 또는 외부 사업자의 긴급한 중단처럼 사전 고지가 어려운 경우에는 먼저 조치한 뒤 가능한 한 빨리 알립니다.
4. 운영자가 서비스를 영구 종료하는 경우에는 회원이 자신의 자료를 확인하거나 내보낼 수 있는 합리적인 기간과 종료 후 처리 방침을 함께 안내합니다. 다만, 법령 또는 보안상 즉시 종료가 필요한 경우에는 예외로 할 수 있습니다.

## 제13조(개인정보 보호와 데이터 처리)

1. 운영자는 개인정보 보호법 등 관련 법령과 별도로 공개한 개인정보처리방침에 따라 개인정보를 처리합니다.
2. 개인정보처리방침은 처리 목적과 항목, 보유기간, 파기, 처리위탁과 국외 이전, 이용자 권리, 자동 수집 기술, 안전성 확보조치와 문의처를 설명합니다.
3. 회원 탈퇴, 작품·회차 삭제와 이용자 콘텐츠 파기의 구체적인 범위·시점은 개인정보처리방침을 따릅니다.
4. 운영자는 GA4와 Meta Pixel의 자동 수집 항목·목적·보유기간·국외 처리와 거부방법을 개인정보처리방침에 공개합니다. 브라우저나 각 사업자의 설정에서 분석·광고 추적을 거부해도 회원가입, 원고 업로드와 AI 분석 등 기본 기능의 이용을 제한하지 않습니다.

## 제14조(회원에 대한 통지)

1. 운영자는 회원이 제공한 이메일, 서비스 내 알림, 팝업 또는 공지사항으로 개별 통지를 할 수 있습니다.
2. 다수 회원에게 공통으로 적용되는 사항은 서비스 공지사항에 7일 이상 게시하는 방법으로 개별 통지를 갈음할 수 있습니다. 다만, 회원의 권리·의무에 중대한 영향을 주는 사항은 합리적으로 가능한 개별 연락 수단을 함께 사용합니다.
3. 회원이 최신 연락처를 제공하지 않아 통지를 받지 못한 경우 운영자는 책임 있는 범위에서 다시 안내할 수 있도록 노력합니다.

## 제15조(책임과 면책)

1. 운영자는 관련 법령과 이 약관에 따라 서비스를 성실히 제공하고 합리적인 기술적·관리적 보호조치를 취합니다.
2. 운영자는 무료 베타의 중단 없는 제공, 모든 오류의 부재, AI 결과의 정확성·완전성 또는 특정 목적 적합성을 보증하지 않습니다.
3. 운영자는 천재지변, 통신망·클라우드·외부 AI 사업자의 장애, 회원의 귀책사유 등 운영자가 합리적으로 통제하기 어려운 사유로 발생한 손해에 대해 책임을 지지 않습니다. 다만, 운영자의 고의 또는 중대한 과실이 있는 경우는 예외입니다.
4. 회원이 이용자 콘텐츠에 필요한 권리를 확보하지 않거나 이 약관을 위반하여 운영자 또는 제3자에게 손해를 발생시킨 경우 회원은 자신의 귀책 범위에서 책임을 부담합니다.
5. 이 조의 어떤 내용도 관련 법령에 따라 배제하거나 제한할 수 없는 운영자의 책임 또는 소비자의 권리를 제한하지 않습니다.

## 제16조(준거법과 분쟁 해결)

1. 이 약관과 서비스 이용계약에는 대한민국 법령을 적용합니다.
2. 운영자와 회원은 서비스 이용과 관련한 분쟁을 원만하게 해결하기 위해 성실히 협의합니다.
3. 협의로 해결되지 않는 분쟁은 민사소송법 등 관련 법령에 따른 관할 법원에서 해결합니다.

