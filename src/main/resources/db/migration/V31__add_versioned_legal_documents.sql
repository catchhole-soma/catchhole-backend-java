## 제8조(AI 처리와 자동화된 결정)

1. 운영자는 회원이 요청한 원고 분석을 위해 필요한 원고 구간과 기존 설정을 AI 모델에 입력하고 설정 후보·비교 의견·원문 근거를 생성합니다.
2. 이용자는 결과를 확인하고 수정·제외·확정할 수 있습니다. AI 결과만으로 이용자의 권리 또는 의무에 법적 효과나 이에 준하는 중대한 영향을 주는 결정을 하지 않습니다.
3. 운영자는 이용자 원고와 분석 결과를 CatchHole 또는 외부 사업자의 범용 모델 학습, 미세조정 또는 평가 데이터로 사용하지 않습니다.
4. OpenAI API 요청에는 `store: false`를 적용하고 운영 계정의 데이터 공유를 활성화하지 않습니다. 제공자의 안전·오남용 방지 로그는 원칙적으로 최대 30일 보관될 수 있습니다.
5. AI 분석 항목, 주요 처리 기준, 결과의 한계 또는 데이터 처리에 관한 설명은 제14조의 연락처로 요청할 수 있습니다.
6. 향후 법적 또는 이에 준하는 중대한 효과를 발생시키는 자동화된 결정을 도입하면 적용 전에 기준과 절차, 설명·검토·거부 권리와 인간의 개입 방법을 별도로 고지합니다.

## 제9조(개인정보의 파기)

1. 운영자는 보유기간이 지나거나 처리 목적이 달성되는 등 개인정보가 불필요하게 된 경우 지체 없이 파기합니다.
2. 회원 탈퇴 요청을 받으면 즉시 기존 세션과 신규 처리를 차단하고, 운영계의 계정·원고·업로드 파일·설정·AI 결과와 동의 기록 삭제를 시작하여 24시간 이내 완료합니다. 이 24시간은 취소 유예기간이 아니라 저장소별 삭제와 실패 재시도를 위한 처리 목표입니다.
3. 전자적 파일과 데이터베이스 기록은 복구하기 어렵도록 삭제하고 객체 저장소의 현재 객체·과거 버전·delete marker, 캐시와 인증 토큰도 함께 제거합니다. 종이 문서를 보관하는 경우 분쇄 또는 소각합니다.
4. 백업 데이터는 운영 시스템과 분리하여 접근을 제한하고 운영계 삭제 후 최대 30일 이내 자동 만료합니다. 삭제된 정보는 장애 복구 과정에서 운영계에 다시 반영하지 않습니다.
5. 원고 내용을 포함하지 않는 삭제 요청·완료·실패 감사 이력은 재시도와 분쟁 대응을 위해 1년간 분리 보관한 뒤 삭제합니다.
6. 회원과 무관한 법률 문서 원문과 버전 이력은 당시 고지 내용을 증명하기 위해 계속 보존합니다.
7. 다른 법령에 따라 계속 보관해야 하는 정보는 다른 정보와 분리하여 접근을 제한하고 법정 기간이 끝난 뒤 파기합니다.

