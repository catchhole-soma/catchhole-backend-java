                AND published_at IS NOT NULL
                AND retired_at IS NULL)
            OR (status = 'RETIRED'
                AND effective_date IS NOT NULL
                AND published_at IS NOT NULL
                AND retired_at IS NOT NULL
                AND retired_at >= published_at)
        )
